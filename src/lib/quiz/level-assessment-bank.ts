export function buildFallbackLevelAssessment(seedOffset = 0): QuizQuestion[] {
  const levels: CefrLevelCode[] = ["A1", "A2", "B1", "B2", "C1", "C2"];
  const ordered: QuizQuestion[] = [];

  for (const lvl of levels) {
    const group = LEVEL_ASSESSMENT_BANK.filter((q) => q.cefrLevel === lvl);
    const rotated =
      group.length > 0
        ? group.map((_, idx) => group[(idx + seedOffset) % group.length])
        : [];
    ordered.push(...rotated);
  }

  return ordered.slice(0, LEVEL_ASSESSMENT_QUESTION_COUNT);
}
