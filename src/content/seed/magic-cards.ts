type RawWordTuple = [string, MagicWordPos, string, string, string];

function expandWords(cardId: string, tuples: RawWordTuple[]): MagicWordItem[] {
  return tuples.map(([word, pos, ipa, meaning, example], idx) => ({
    id: `${cardId}-w${idx + 1}`,
    word,
    lemma: word.toLowerCase().replace(/[^a-z0-9\s'-]/g, "").trim(),
    pos,
    ipa,
    meaning,
    example,
  }));
}

